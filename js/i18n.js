function applyLanguage(lang) {
  const dict = translations[lang] || translations.pt;
  document.documentElement.lang = lang === "en" ? "en" : "pt-BR";

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    const value = dict[key];
    if (value == null) return;

    if (el.hasAttribute("data-i18n-html")) {
      el.innerHTML = value;
    } else {
      el.textContent = value;
    }
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const key = el.getAttribute("data-i18n-aria");
    const value = dict[key];
    if (value != null) el.setAttribute("aria-label", value);
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((el) => {
    const key = el.getAttribute("data-i18n-alt");
    const value = dict[key];
    if (value != null) el.setAttribute("alt", value);
  });

  const title = dict["meta.title"];
  if (title) document.title = title;

  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc && dict["meta.description"]) {
    metaDesc.setAttribute("content", dict["meta.description"]);
  }

  const langBtn = document.getElementById("lang-toggle");
  if (langBtn) {
    langBtn.textContent = dict["ctrl.lang"];
    langBtn.setAttribute("aria-label", dict["ctrl.langAria"]);
  }

  const cvLink = document.getElementById("cv-download");
  if (cvLink) {
    const cvFile =
      lang === "en" ? "GiuliaFreulonCV-EN.pdf" : "GiuliaFreulonCV-PT.pdf";
    cvLink.href = `pdf/${cvFile}`;
    cvLink.setAttribute("download", cvFile);
  }

  const themeBtn = document.getElementById("theme-toggle");
  if (themeBtn) {
    const theme = document.documentElement.getAttribute("data-theme") || "dark";
    themeBtn.setAttribute(
      "aria-label",
      theme === "dark" ? dict["ctrl.themeAriaLight"] : dict["ctrl.themeAriaDark"]
    );
  }

  const hamburger = document.querySelector(".hamburger");
  if (hamburger) {
    const isOpen = hamburger.classList.contains("active");
    hamburger.setAttribute(
      "aria-label",
      isOpen ? dict["nav.menuClose"] : dict["nav.menuOpen"]
    );
  }
}
